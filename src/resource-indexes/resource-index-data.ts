function glossaryRecord(
  planningId: string,
  title: string,
  resourceType: ResourceType,
  relatedUnits: readonly string[],
  versionZh: string,
  versionEn: string,
  reviewedOn = '2026-08-26',
): ResourceIndexRecord {
  const anchor = planningId.toLowerCase();
  return {
    planningId,
    group: 'glossary',
    title: same(title),
    href: localized(`/glossary/#${anchor}`, `/en/glossary/#${anchor}`),
    resourceType,
    prerequisites: [],
    relatedUnits,
    hardwareGate: noHardware,
    versionGate: localized(versionZh, versionEn),
    reviewedOn,
  };
}

function sourceRecord(
  planningId: string,
  title: LocalizedText,
  resourceType: 'publishing-interface' | 'cuda-version-record' | 'cpp-language-record' | 'linux-tool-record' | 'architecture-record' | 'historical-record',
  relatedUnits: readonly string[],
  versionGate: LocalizedText,
  reviewedOn = '2026-08-24',
  sourceAccessDate = '2026-08-24',
): ResourceIndexRecord {
  const anchor = planningId.toLowerCase();
  return {
    planningId,
    group: 'sources',
    title,
    href: localized(`/sources-and-versions/#${anchor}`, `/en/sources-and-versions/#${anchor}`),
    resourceType,
    prerequisites: [],
    relatedUnits,
    hardwareGate: noHardware,
    versionGate,
    reviewedOn,
    sourceAccessDate,
  };
}

